// Scopes the approved prototype stylesheet (src/site/styles/xen.source.css, a verbatim
// copy of Justechltd/Xen-Web-Redesign site/css/xen.css) under `.xen`, so it styles the
// public site without touching the Tailwind/shadcn admin.
//
//   node scripts/scope-xen-css.mjs
//
// Never hand-edit xen.css — edit the source (or the patches below) and re-run.
// Rewrites:
//   :root, body           -> .xen          (tokens and base type live on the wrapper)
//   body::before          -> .xen::before
//   body[data-page=…] X   -> .xen[data-page=…] X
//   body.pano X           -> .xen.pano X
//   .js X                 -> .xen.js X     (the "js" class is added on mount, so
//                                            prerendered HTML is visible without JS)
//   html                  -> html          (left global; var(--nav-h) inlined)
//   anything else         -> .xen X
// Patches (each one is signed off in docs/redesign/DEVIATIONS.md):
//   - overflow-x: hidden on the wrapper becomes `clip`: `hidden` would make the wrapper a
//     scroll container and break the sticky header. Body gets overflow-x hidden instead.
//   - C4: Bengali fallbacks in the font stacks so "৳" renders properly (Manrope and Gloock
//     have no Taka sign). Self-hosted Noto Bengali subsets (OFL) holding only U+09F3,
//     public/fonts/taka-*.woff2, ~2 KB total.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src/site/styles/xen.source.css");
const out = path.join(root, "src/site/styles/xen.css");

const scopeSelector = (sel) => {
  const s = sel.trim();
  if (s === ":root" || s === "body") return ".xen";
  if (s === "html") return "html";
  if (s.startsWith("body::")) return ".xen" + s.slice(4);
  if (s.startsWith("body[") || s.startsWith("body.")) return ".xen" + s.slice(4);
  if (s.startsWith(".js ")) return ".xen.js " + s.slice(4);
  return ".xen " + s;
};

const inKeyframes = (node) => {
  for (let p = node.parent; p; p = p.parent) if (p.type === "atrule" && /keyframes$/i.test(p.name)) return true;
  return false;
};

const css = fs.readFileSync(src, "utf8");
const result = postcss.parse(css);

result.walkRules((rule) => {
  if (inKeyframes(rule)) return;
  rule.selectors = rule.selectors.map(scopeSelector);
  const isHtml = rule.selectors.length === 1 && rule.selectors[0] === "html";
  rule.walkDecls((d) => {
    if (isHtml) d.value = d.value.replace("var(--nav-h)", "72px");
    if (rule.selector === ".xen" && d.prop === "overflow-x" && d.value === "hidden") d.value = "clip";
    if (rule.selector === ".xen" && d.prop === "--f-body") d.value = d.value.replace('"Manrope",', '"Manrope", "Xen Taka Sans",');
    if (rule.selector === ".xen" && d.prop === "--f-display") d.value = d.value.replace('"Gloock",', '"Gloock", "Xen Taka Serif",');
  });
});

const header = `/* GENERATED by scripts/scope-xen-css.mjs from xen.source.css. Do not edit. */\n`;
const extra = `
/* Added for production (see scripts/scope-xen-css.mjs) */
@font-face { font-family: "Xen Taka Sans"; src: url(/fonts/taka-sans.woff2) format("woff2"); font-weight: 100 900; font-display: swap; unicode-range: U+09F3; }
@font-face { font-family: "Xen Taka Serif"; src: url(/fonts/taka-serif.woff2) format("woff2"); font-weight: 400; font-display: swap; unicode-range: U+09F3; }
body.xen-public { margin: 0; background: #f5f6f2; overflow-x: hidden; }
.xen { min-height: 100vh; }
/* The prototype has no CSS reset, so its <dl> lists (facts, specs) keep the browser's 1em
   block margin. Tailwind's preflight removes it; restore it to match the approved spacing. */
.xen dl { margin-block: 1em; }
/* Booking card states that have no inputs (loading / no slots) reuse the form card look. */
.xen div.lead { background: #fff; color: var(--text); border-radius: 22px; padding: clamp(22px, 3.5vw, 36px); }
.xen .band--dark:has(.enquiry) div.lead { box-shadow: 0 30px 60px -30px rgba(15,61,39,.35), 0 0 0 1px #d7e7dc; }
.xen form.lead textarea { resize: vertical; min-height: 0; }
`;
fs.writeFileSync(out, header + result.toString() + extra);

const check = fs.readFileSync(out, "utf8");
for (const needle of ['.xen[data-page="home"] .hero', ".xen.pano .hero-photo", ".xen.js .reveal", "overflow-x: clip", "Xen Taka Sans"]) {
  if (!check.includes(needle)) { console.error("scope-xen-css: missing expected rule:", needle); process.exit(1); }
}
console.log("scope-xen-css: wrote", path.relative(root, out));
